// Writes supabase/seed-listings.sql from the real (non ASMS-PREVIEW) listings in
// content/content.json, so listings prepared before Supabase existed can be loaded
// into it. Run it in the Supabase SQL editor after schema.sql; it is safe to re-run
// (rows are matched by reference). Photos are stored as their storage paths
// (/media/properties/x.webp -> properties/x.webp); upload the files themselves to
// the "media" bucket under the same paths.
// Usage: node scripts/listings-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const content = JSON.parse(readFileSync(join(root, "content", "content.json"), "utf8"));
const listings = content.properties.filter((p) => !p.reference.startsWith("ASMS-PREVIEW"));

const snake = (k) => k.replace("SqFt", "Sqft").replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const SKIP = new Set([]);
const SAFE_PATH = /^[a-z0-9_-]+(\/[A-Za-z0-9_-]+)*\/[A-Za-z0-9_-]+\.(webp|jpe?g|png)$/;
const storageImages = (images) => images.map((img) => {
  const path = img.src.replace(/^\/media\//, "");
  if (!img.src.startsWith("/media/") || !SAFE_PATH.test(path)) throw new Error(`Photo is not a storage path: ${img.src}`);
  return { path, alt: img.alt ?? "" };
});
const quote = (s) => `'${String(s).replaceAll("'", "''")}'`;
const literal = (key, v) => {
  if (v === null || v === undefined) return "null";
  if (key === "amenities") return `array[${v.map(quote).join(", ")}]::text[]`;
  if (key === "images") return `${quote(JSON.stringify(storageImages(v)))}::jsonb`;
  if (key === "nearby" || key === "documents") return `${quote(JSON.stringify(v))}::jsonb`;
  if (typeof v === "boolean" || typeof v === "number") return String(v);
  return quote(v);
};

const statements = listings.map((p) => {
  const keys = Object.keys(p).filter((k) => !SKIP.has(k));
  const cols = keys.map(snake);
  const updates = cols.filter((c) => c !== "reference").map((c) => `  ${c} = excluded.${c}`);
  return `-- ${p.reference}: ${p.title}
insert into public.properties (${cols.join(", ")})
values (${keys.map((k) => literal(k, p[k])).join(",\n  ")})
on conflict (reference) do update set
${updates.join(",\n")};`;
});

const out = `-- Generated by scripts/listings-sql.mjs from content/content.json. Do not edit by hand.
-- Run in the Supabase SQL editor after schema.sql. Re-running updates the same rows.
begin;
${statements.join("\n\n")}
commit;
`;
writeFileSync(join(root, "supabase", "seed-listings.sql"), out);
console.log(`Wrote ${listings.length} listing(s) to supabase/seed-listings.sql`);

// ---------------------------------------------------------------- products --
// supabase/seed-products.sql: the catalogue in content.json as published products.
// Photos in public/products/ go to the "media" bucket as products/<file>; their
// Creative Commons credits travel with them (image_credit) so the product pages
// keep crediting the photographers.
const productStorage = (src) => {
  const path = src.replace(/^\/(media\/)?/, "");
  if (!SAFE_PATH.test(path)) throw new Error(`Product photo is not a storage path: ${src}`);
  return path;
};
const order = new Map();
const productStatements = content.products.map((p) => {
  const n = (order.get(p.categoryId) ?? 0) + 1;
  order.set(p.categoryId, n);
  const row = {
    slug: quote(p.slug), category_id: quote(p.categoryId), name: quote(p.name), summary: quote(p.summary),
    specs: `${quote(JSON.stringify(p.specs ?? []))}::jsonb`, unit: quote(p.unit),
    suitable_use: literal("", p.suitableUse), availability: literal("", p.availability),
    image_path: p.image ? quote(productStorage(p.image.src)) : "null",
    image_alt: p.image ? quote(p.image.alt || p.name) : "null",
    image_credit: p.image?.credit ? `${quote(JSON.stringify(p.image.credit))}::jsonb` : "null",
    published: "true", sort_order: String(n),
  };
  const cols = Object.keys(row);
  return `-- ${p.name}
insert into public.products (${cols.join(", ")})
values (${Object.values(row).join(", ")})
on conflict (slug) do update set
${cols.filter((c) => c !== "slug").map((c) => `  ${c} = excluded.${c}`).join(",\n")};`;
});
writeFileSync(join(root, "supabase", "seed-products.sql"), `-- Generated by scripts/listings-sql.mjs from content/content.json. Do not edit by hand.
-- Publishes the product catalogue. Run in the Supabase SQL editor after schema.sql,
-- once the photos are uploaded to the "media" bucket under products/. Safe to re-run.
begin;
${productStatements.join("\n\n")}
commit;
`);
console.log(`Wrote ${productStatements.length} product(s) to supabase/seed-products.sql`);
